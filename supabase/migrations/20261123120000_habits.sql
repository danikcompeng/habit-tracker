-- Hold: habits and their daily check-ins (plans/habit-tracker.md, Feature 1).
--
-- How to apply: Supabase dashboard -> SQL Editor -> New query, paste this
-- whole file, Run. Once. It only creates new things (two tables, four
-- functions, one trigger); it doesn't touch Staple's tables, which share
-- this project. It's one transaction: if anything fails, nothing is kept,
-- so it can simply be run again after fixing the problem.
--
-- tests/db/habits.db.test.ts runs this exact file against real Postgres
-- (PGlite) with Supabase's roles and default privileges, and checks every
-- rule below.

begin;

-- ---------------------------------------------------------------------------
-- habits: one row per habit you track.
-- ---------------------------------------------------------------------------
create table public.habits (
  id uuid primary key default gen_random_uuid(),
  -- Whose habit. Filled from the login token, never from the app.
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  -- Order on screen (smallest first). Each new habit gets a bigger number
  -- than any before it, so it lands at the bottom, even after you reorder
  -- (reordering rewrites them to 0, 1, 2...: every habit took a number from
  -- this counter, so the next one is always bigger than your count).
  position bigint generated by default as identity,
  created_at timestamptz not null default now(),

  -- 1 to 60 characters (char_length counts characters, so an emoji is 1),
  -- with no spaces at either end. The app tidies names before saving
  -- (lib/habit-name.ts), so this is only a backstop.
  constraint habits_name_length check (char_length(name) between 1 and 60),
  constraint habits_name_trimmed check (name !~ '^\s' and name !~ '\s$'),
  -- Lets a check-in point at "this habit AND this owner" (below).
  constraint habits_id_user_id_key unique (id, user_id)
);

create index habits_user_position_idx on public.habits (user_id, position);

-- ---------------------------------------------------------------------------
-- At most 100 habits each. Anyone logged in (the shared demo account too)
-- could call Supabase directly and skip the app, so the limit lives here:
-- this project is shared with Staple, and its storage is shared too.
-- A trigger, not a policy: a count inside a policy can't see the other
-- rows of the same bulk insert, so 1,000 rows in one request would pass.
-- ---------------------------------------------------------------------------
create function public.habits_enforce_limit()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if (select count(*) from public.habits as h where h.user_id = new.user_id) >= 100 then
    raise exception 'habits: limit of 100 reached' using errcode = '54000';
  end if;
  return new;
end;
$$;

create trigger habits_limit
  before insert on public.habits
  for each row execute function public.habits_enforce_limit();

-- ---------------------------------------------------------------------------
-- habit_checkins: "this habit was done on this day". A day is a plain
-- calendar date in YOUR timezone (worked out by the app), never a
-- timestamp, so 23:30 in Toronto can't turn into tomorrow in UTC.
-- Undo = delete the row. A row is never edited.
-- ---------------------------------------------------------------------------
create table public.habit_checkins (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  habit_id uuid not null,
  day date not null,
  created_at timestamptz not null default now(),

  -- One check-in per habit per day. user_id first, so a "this already
  -- exists" error can only ever be about your own rows.
  constraint habit_checkins_pkey primary key (user_id, habit_id, day),
  -- The habit must exist AND be yours: no check-ins on someone else's
  -- habit, even with its id. Deleting a habit deletes its check-ins.
  constraint habit_checkins_habit_fkey foreign key (habit_id, user_id)
    references public.habits (id, user_id) on delete cascade,
  constraint habit_checkins_day_check check (day >= date '2000-01-01')
);

-- "Your check-ins in the last 7 days".
create index habit_checkins_user_day_idx on public.habit_checkins (user_id, day);

-- ---------------------------------------------------------------------------
-- Row Level Security: you can only see and change your own rows.
-- (select auth.uid()) in brackets is Supabase's advice: it's worked out
-- once per query instead of once per row.
-- ---------------------------------------------------------------------------
alter table public.habits enable row level security;
alter table public.habit_checkins enable row level security;

create policy habits_select_own on public.habits
  for select to authenticated using ((select auth.uid()) = user_id);
create policy habits_insert_own on public.habits
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy habits_update_own on public.habits
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy habits_delete_own on public.habits
  for delete to authenticated using ((select auth.uid()) = user_id);

create policy habit_checkins_select_own on public.habit_checkins
  for select to authenticated using ((select auth.uid()) = user_id);
-- A new check-in must be near today: from 60 days ago (the demo's sample
-- history) to tomorrow in UTC (which covers today everywhere on Earth, up to
-- UTC+14). The app is stricter (lib/checkin-day.ts: today, or yesterday
-- just after midnight); this stops anyone calling Supabase directly from
-- filling the table with years of dates. Rows already saved are never
-- affected, so streaks keep growing past 60 days.
create policy habit_checkins_insert_own on public.habit_checkins
  for insert to authenticated with check (
    (select auth.uid()) = user_id
    and day between (now() at time zone 'utc')::date - 60 and (now() at time zone 'utc')::date + 1
  );
create policy habit_checkins_delete_own on public.habit_checkins
  for delete to authenticated using ((select auth.uid()) = user_id);

-- ---------------------------------------------------------------------------
-- Privileges: take everything away, then give back only what the app uses.
-- Why: Supabase gives anon and authenticated ALL on every new table and
-- sequence (including TRUNCATE, which Row Level Security doesn't cover),
-- and Postgres lets anyone (PUBLIC) run a new function.
-- ---------------------------------------------------------------------------
revoke all on table public.habits, public.habit_checkins from anon, authenticated;
-- The counter behind habits.position. Inserting a habit doesn't need any
-- privilege on it; changing it (setval) would break every insert.
revoke all on sequence public.habits_position_seq from anon, authenticated;

grant select, insert, delete on table public.habits to authenticated;
-- Only the name and the order can change, never the id, owner or date made.
grant update (name, position) on table public.habits to authenticated;
grant select, insert, delete on table public.habit_checkins to authenticated;

-- ---------------------------------------------------------------------------
-- habit_streaks: each habit's current streak, counted from the check-ins.
-- Never stored, so an undo or a deleted day can't leave it wrong.
--
-- A streak is the run of back-to-back days with a check-in that ends
-- TODAY, or YESTERDAY if today isn't done yet (the day isn't over, so the
-- streak is still alive). Habits with no such run aren't returned: 0.
--
-- How: number each habit's days 1, 2, 3... in date order and subtract that
-- number from the date. Back-to-back days give the same answer (Mon-1,
-- Tue-2, Wed-3 are all the same date), so each run of days shares one
-- value. Then keep the run whose last day is today or yesterday.
--
-- security invoker: runs as YOU, so Row Level Security still applies.
-- search_path = '': every name is written in full (public.habit_checkins),
-- so nobody can swap in a lookalike table.
-- ---------------------------------------------------------------------------
create function public.habit_streaks(p_today date)
returns table (habit_id uuid, current_streak integer)
language sql
stable
security invoker
set search_path = ''
as $$
  with numbered as (
    select
      c.habit_id,
      c.day,
      c.day - (row_number() over (partition by c.habit_id order by c.day))::integer as run_key
    from public.habit_checkins as c
    where c.user_id = (select auth.uid())
      and c.day <= p_today
  ),
  runs as (
    select n.habit_id, max(n.day) as last_day, count(*)::integer as days
    from numbered as n
    group by n.habit_id, n.run_key
  )
  select r.habit_id, r.days
  from runs as r
  where r.last_day >= p_today - 1
$$;

-- ---------------------------------------------------------------------------
-- reorder_habits: puts ALL your habits in the order of the ids you pass.
-- The list must be exactly your habits, each once. If it isn't (say the
-- screen was out of date and a habit was added or deleted elsewhere), it
-- changes nothing and fails with code HR001, so the app can reload
-- instead of saving an order nobody saw.
-- (plpgsql, not sql, because it needs to raise errors and count rows.)
-- ---------------------------------------------------------------------------
create function public.reorder_habits(p_ids uuid[])
returns integer
language plpgsql
volatile
security invoker
set search_path = ''
as $$
declare
  moved integer;
begin
  if p_ids is null
     or cardinality(p_ids) <> (select count(distinct t.id) from unnest(p_ids) as t(id)) then
    raise exception 'reorder_habits: every id must appear once' using errcode = '22023';
  end if;

  if cardinality(p_ids) <> (select count(*) from public.habits as h where h.user_id = (select auth.uid())) then
    raise exception 'reorder_habits: the list is out of date' using errcode = 'HR001';
  end if;

  update public.habits as h
     set position = t.ord - 1
    from unnest(p_ids) with ordinality as t(id, ord)
   where h.id = t.id
     and h.user_id = (select auth.uid());

  get diagnostics moved = row_count;
  -- Same count but some ids weren't yours (or no longer exist): undo it all.
  if moved <> cardinality(p_ids) then
    raise exception 'reorder_habits: the list is out of date' using errcode = 'HR001';
  end if;
  return moved;
end;
$$;

-- ---------------------------------------------------------------------------
-- reseed_demo_habits: replaces the CALLER's habits and check-ins with the
-- list passed in, all at once. "Try the demo" uses it to put the sample
-- habits back (plans/habit-tracker.md, Feature 2), and the app only calls
-- it for the demo account.
--
-- Why one function instead of separate requests: in one transaction, a
-- failure keeps the old data instead of half a seed, and the lock makes two
-- demo sign-ins at the same moment take turns instead of leaving two copies.
--
-- security invoker: Row Level Security, the 100-habit limit and the
-- check-in date window all still apply. Anyone else calling it can only
-- ever replace their own habits.
--
-- p_habits: [{ "name": "...", "created_at": "<timestamp>", "days": ["YYYY-MM-DD", ...] }, ...]
-- Habits are added in list order, so that's the order on screen.
-- ---------------------------------------------------------------------------
create function public.reseed_demo_habits(p_habits jsonb)
returns integer
language plpgsql
volatile
security invoker
set search_path = ''
as $$
declare
  me uuid := (select auth.uid());
  item jsonb;
  new_id uuid;
  added integer := 0;
begin
  if me is null then
    raise exception 'reseed_demo_habits: not logged in' using errcode = '42501';
  end if;
  if p_habits is null or jsonb_typeof(p_habits) <> 'array' then
    raise exception 'reseed_demo_habits: expected a list of habits' using errcode = '22023';
  end if;

  -- One seed per user at a time; released when this transaction ends.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('hold.reseed_demo_habits:' || me::text, 0));

  delete from public.habits as h where h.user_id = me;

  for item in select value from jsonb_array_elements(p_habits) loop
    insert into public.habits (name, created_at)
    values (item ->> 'name', coalesce((item ->> 'created_at')::timestamptz, now()))
    returning id into new_id;

    insert into public.habit_checkins (habit_id, day)
    select new_id, d.value::date
    from jsonb_array_elements_text(coalesce(item -> 'days', '[]'::jsonb)) as d(value);

    added := added + 1;
  end loop;

  return added;
end;
$$;

revoke all on function public.habits_enforce_limit() from public, anon, authenticated;
revoke all on function public.habit_streaks(date) from public, anon, authenticated;
revoke all on function public.reorder_habits(uuid[]) from public, anon, authenticated;
revoke all on function public.reseed_demo_habits(jsonb) from public, anon, authenticated;
grant execute on function public.habit_streaks(date) to authenticated;
grant execute on function public.reorder_habits(uuid[]) to authenticated;
grant execute on function public.reseed_demo_habits(jsonb) to authenticated;

commit;
